#[test]
fn matches_the_generated_high_precision_reference_grid() {
    for case in CASES {
        let actual = evaluate(*case);
        if case.expected.is_infinite() {
            assert_eq!(
                actual.is_infinite() && actual.is_sign_positive(),
                case.expected.is_sign_positive(),
                "{:?}({}, {}) expected {:?}, got {:?}",
                family_name(case.family),
                case.order,
                case.x,
                case.expected,
                actual
            );
            continue;
        }
        let tolerance = case.absolute + case.relative * case.expected.abs();
        assert!(
            (actual - case.expected).abs() <= tolerance,
            "{}({}, {}): expected {:.17e}, got {:.17e}, tolerance {:.17e}",
            family_name(case.family),
            case.order,
            case.x,
            case.expected,
            actual,
            tolerance
        );
    }
}

fn evaluate(case: Case) -> f64 {
    let x = case.x.abs();
    let mut never = || Ok(());
    let mut value = match case.family {
        Family::I => bessel_i(case.order, x, &mut never),
        Family::J => bessel_j(case.order, x, &mut never),
        Family::K => bessel_k(case.order, x, &mut never),
        Family::Y => bessel_y(case.order, x, &mut never),
    }
    .expect("generated references have valid kernel domains");
    if matches!(case.family, Family::I | Family::J)
        && case.x.is_sign_negative()
        && case.order % 2 == 1
    {
        value = -value;
    }
    value
}

const fn family_name(family: Family) -> &'static str {
    match family {
        Family::I => "I",
        Family::J => "J",
        Family::K => "K",
        Family::Y => "Y",
    }
}
